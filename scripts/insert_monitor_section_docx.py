def find_chapter3_paragraph(doc: Document):
    for p in doc.paragraphs:
        if p.text.strip().startswith(CH3_MARKER):
            return p
    return None


def insert_section(doc: Document, anchor, blocks: list[tuple[str, str]]) -> int:
    """Insert blocks in reading order before anchor (forward insert before fixed anchor)."""
    count = 0
    for style, text in blocks:
        new_p = anchor.insert_paragraph_before(text)
        new_p.style = style
        count += 1
    return count


def main() -> int:
    if not DOC_PATH.exists():
        print(f"Missing: {DOC_PATH}", file=sys.stderr)
        return 1

    doc = Document(str(DOC_PATH))
    anchor = find_chapter3_paragraph(doc)
    if anchor is None:
        print(f"Could not find anchor: {CH3_MARKER!r}", file=sys.stderr)
        return 1

    inserted = insert_section(doc, anchor, SECTION_BLOCKS)
    doc.save(str(DOC_PATH))
    sys.stdout.buffer.write(
        f"Inserted {inserted} paragraphs before Chapter 3\n".encode("utf-8")
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
